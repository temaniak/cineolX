#!/usr/bin/env python3
"""Prepare float original-224 converter kernels from Cineol-X desktop sources.

No ROM, bank or Reflexion dependency. Runtime has no coefficient preparation.
Run from any directory; --check detects stale checked-in tables.
"""
import argparse
import cmath
import hashlib
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ADC = ROOT / 'desktop/adc22448.hpp'
DAC = ROOT / 'desktop/dac22448.hpp'
OUTPUT = ROOT / 'daisy/src/Io224Tables.hpp'


def rows(path):
    source = path.read_text()
    body = re.search(r'const double rows\[modes\]\[4\]=\{(.*?)\};', source, re.S).group(1)
    return [[float(v) for v in row.split(',')] for row in re.findall(r'\{([^{}]+)\}', body)]


def coefficients(p, seconds):
    x = p * seconds
    e = cmath.exp(x)
    if abs(x) < 1e-3:
        em1 = x * (1 + x / 2 + x*x / 6 + x*x*x / 24)
        em1x = x*x * (.5 + x / 6 + x*x / 24 + x*x*x / 120)
    else:
        em1, em1x = e - 1, e - 1 - x
    return e, em1 / p, em1x / (p*p)


def bessel(x):
    total = term = 1.
    for k in range(1, 30):
        term *= x*x / (4*k*k)
        total += term
    return total


def generate():
    # These are the desktop Adc48 analytic FOH/interpolator equations.
    h = []
    for n in range(128):
        t, r, fc = n - 63.5, 2*n/127 - 1, 22000/192000
        h.append(math.sin(2*math.pi*fc*t)/(math.pi*t)
                 * bessel(8*math.sqrt(max(0., 1-r*r))) / bessel(8) * 4)
    h.append(0.)
    poles, residues, z, whole, tail, startup = [], [], [], [], [], []
    for pr, pi, rr, ri in rows(ADC):
        p, residue = complex(pr, pi), complex(rr, ri) * (2 if pi else 1) * .6714903705341165
        a, step, ramp = coefficients(p, 1/192000)
        state = [h[0]*192000*ramp]
        startup.append(residue*state[0])
        for n in range(128):
            state.append(a*state[-1]+h[n]*step+(h[n+1]-h[n])*192000*ramp)
        poles.append(p)
        residues.append(residue)
        z.append(state)
        whole.append(cmath.exp(p/48000))
        tail.append(residue*state[128])
    fir, fractional = [], []
    for phase in range(64):
        fraction = 585805 % 187500 + phase*187500
        fractional.append([cmath.exp(p*fraction/576000000000) for p in poles])
        weights = []
        for j in range(33):
            time = (j-1)*12000000 + fraction
            y = 0.
            if time < 0:
                if time >= -3000000:
                    partial = (time+3000000)/576000000000
                    for k, p in enumerate(poles):
                        y += (residues[k]*coefficients(p, partial)[2]*h[0]*192000).real
                    y += -1.9027652288899368e-11*.6714903705341165*h[0]*partial*192000
            else:
                segment, partial = time//3000000, (time % 3000000)/576000000000
                for k, p in enumerate(poles):
                    a, step, ramp = coefficients(p, partial)
                    value = a*z[k][segment]+h[segment]*step+(h[segment+1]-h[segment])*192000*ramp
                    y += (residues[k]*value).real
                y += -1.9027652288899368e-11*.6714903705341165*(h[segment]+(h[segment+1]-h[segment])*partial*192000)
            weights.append(y)
        fir.append(weights)
    # Omit only the desktop's negligible -500 kHz output mode (<7e-11 DC).
    drows = rows(DAC)[1:]
    dwhole, dweights = [], []
    for pr, pi, rr, ri in drows:
        p = complex(pr, pi)
        dweights.append(complex(rr, ri)/p*(2 if pi else 1))
        dwhole.append(cmath.exp(p*28125000/576000000000)-1)
    dfractional = [[cmath.exp(complex(pr, pi)*(93750-643405 % 93750+phase*93750)/576000000000)-1
                   for pr, pi, _, _ in drows] for phase in range(300)]

    def literal(value):
        return float(value).hex() + 'f'

    def array(name, values, shape, complex_values=False):
        def format_value(v):
            if isinstance(v, list):
                return '{' + ','.join(format_value(x) for x in v) + '}'
            if complex_values:
                return '{' + literal(v.real) + ',' + literal(v.imag) + '}'
            return literal(v)
        kind = 'Complex' if complex_values else 'float'
        return f'inline constexpr {kind} {name}{shape}=' + format_value(values) + ';\n'

    sha = hashlib.sha256(ADC.read_bytes()+DAC.read_bytes()).hexdigest()
    out = ('// Generated by ../tools/generate_io_tables.py; do not edit.\n'
           '// Desktop ADC+DAC source SHA256: '+sha+'\n'
           '#pragma once\nnamespace native_hall::daisy_io224 {\n'
           'struct Complex {float re,im;};\n')
    for name, values, shape, is_complex in [
        ('input_fir', fir, '[64][33]', False),
        ('input_fractional', fractional, '[64][6]', True),
        ('input_whole', whole, '[6]', True), ('input_tail', tail, '[6]', True),
        ('input_startup', startup, '[6]', True),
        ('output_fractional', dfractional, '[300][6]', True),
        ('output_whole', dwhole, '[6]', True), ('output_weights', dweights, '[6]', True)]:
        out += array(name, values, shape, is_complex)
    return out + '} // namespace native_hall::daisy_io224\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('Stale Daisy I/O tables; run native-hall/daisy/tools/generate_io_tables.py')
        print('Daisy original-224 tables match current Cineol-X ADC/DAC sources')
    else:
        OUTPUT.write_text(result)
        print(OUTPUT)
